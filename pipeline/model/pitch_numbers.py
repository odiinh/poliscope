"""Brief C step 9: write docs/pitch_numbers.md from data/public/signal.json as plain sentences."""

from pipeline.model.common import PUBLIC, ROOT, read_json

LABELS = {
    "gdp_pc_rel": "real GDP per capita growth relative to the US",
    "debt_pc_rel": "debt per capita growth relative to the median state",
}


def sentences(s):
    lo, hi = s["skill_ci95"]
    if lo <= 0 <= hi:
        spans = "spans zero, so the precedent signal is not distinguishable from the baseline"
    elif hi < 0:
        spans = (
            "lies below zero, so precedents did worse than the baseline out of sample"
        )
    else:
        spans = "lies above zero, so precedents beat the baseline out of sample"
    return [
        f"Walk-forward over cohorts {', '.join(map(str, s['cohorts']))}, n = {s['n_test']} out-of-sample terms.",
        f"Skill against the prior-trend baseline is {s['skill']:.1%} (95% CI {lo:.1%} to {hi:.1%}); the interval {spans}.",
        f"Skill against the party comparator is {s['skill_vs_party']:.1%}.",
        f"Permutation p-value over 200 shuffles is {s['permutation_p']:.3f}.",
        f"Brier score for beating the benchmark: {s['brier']['knn']:.3f} with precedents vs {s['brier']['baseline']:.3f} for the baseline.",
    ]


def main():
    lines = [
        "# Pitch numbers",
        "",
        "Generated by `python -m pipeline.model.pitch_numbers` from `data/public/signal.json`.",
        "",
    ]
    for s in read_json(PUBLIC / "signal.json"):
        lines += [
            f"## {LABELS[s['metric']]}",
            "",
            *[f"- {x}" for x in sentences(s)],
            "",
        ]
    (ROOT / "docs/pitch_numbers.md").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
